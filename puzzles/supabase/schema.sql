-- 1. Player profiles: one row per sign-up, created automatically by the trigger below.
create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  username    text not null default 'player',
  created_at  timestamptz not null default now()
);

-- 2. Activity log: every puzzle attempt (kind 'a'), seed (kind 's') and reset (kind 'z'),
--    stored exactly as the browser records it. Ratings and dashboard numbers are
--    derived from this log, so nothing is stored twice.
create table if not exists public.activity_events (
  id           bigint generated always as identity primary key,
  user_id      uuid not null references auth.users (id) on delete cascade,
  event_id     text not null,                       -- generated by the page, unique per player
  phase        text not null check (phase in ('o', 'm', 'e')),
  kind         text not null check (kind in ('a', 's', 'z')),
  occurred_at  bigint not null,                     -- milliseconds since epoch (browser clock)
  payload      jsonb not null,
  created_at   timestamptz not null default now(),
  unique (user_id, event_id)
);
create index if not exists activity_events_user_time
  on public.activity_events (user_id, occurred_at);

-- 3. Row Level Security: a player can only see and write their own rows.
alter table public.profiles        enable row level security;
alter table public.activity_events enable row level security;

drop policy if exists "profiles: read own"    on public.profiles;
drop policy if exists "profiles: update own"  on public.profiles;
drop policy if exists "events: read own"      on public.activity_events;
drop policy if exists "events: insert own"    on public.activity_events;

create policy "profiles: read own"   on public.profiles for select using (auth.uid() = id);
create policy "profiles: update own" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);
create policy "events: read own"     on public.activity_events for select using (auth.uid() = user_id);
create policy "events: insert own"   on public.activity_events for insert with check (auth.uid() = user_id);

-- Events are append-only by design (no update/delete policy). Progress resets are
-- recorded as 'z' events, so history is never lost.

-- 4. Create a profile automatically when someone signs up.
create or replace function public.handle_new_player()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, username)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'username'), ''), 'player')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_player_created on auth.users;
create trigger on_auth_player_created
  after insert on auth.users
  for each row execute function public.handle_new_player();
